create table workspace_model_providers (
    id bigint generated by default as identity,
    workspace_id bigint not null,
    provider_kind varchar(40) not null,
    wire_protocol varchar(40) not null,
    display_name varchar(120) not null,
    base_url varchar(500) not null,
    api_key text,
    default_model varchar(160) not null,
    enabled_models_json text not null,
    priority_order integer not null default 100,
    enabled boolean not null default true,
    last_status varchar(40),
    last_latency_ms bigint,
    last_checked_at timestamp(6) without time zone,
    last_error text,
    created_by_google_sub varchar(120) not null,
    created_at timestamp(6) without time zone not null,
    updated_at timestamp(6) without time zone not null,
    deleted_at timestamp(6) without time zone,
    constraint workspace_model_providers_pkey primary key (id),
    constraint fk_workspace_model_providers_workspace
        foreign key (workspace_id) references workspaces (id),
    constraint workspace_model_providers_kind_check check (
        provider_kind in (
            'OPENAI', 'ANTHROPIC', 'GOOGLE', 'OPENROUTER', 'DEEPSEEK',
            'XAI', 'GROQ', 'OLLAMA', 'CUSTOM_OPENAI'
        )
    ),
    constraint workspace_model_providers_protocol_check check (
        wire_protocol in (
            'OPENAI_CHAT', 'OPENAI_RESPONSES', 'ANTHROPIC_MESSAGES',
            'GOOGLE_GEMINI', 'OLLAMA_NATIVE'
        )
    ),
    constraint workspace_model_providers_last_status_check check (
        last_status is null
        or last_status in ('CONNECTED', 'UNREACHABLE', 'TOKEN_INVALID', 'TIMEOUT', 'RATE_LIMITED', 'FAILED')
    )
);

create index if not exists idx_workspace_model_providers_ws_priority
    on workspace_model_providers (workspace_id, deleted_at, enabled, priority_order, id);

alter table workspace_agents
    add column if not exists model_provider_id bigint;

alter table workspace_agents
    add column if not exists model_id varchar(160);

alter table workspace_agents
    add column if not exists fallback_model_id varchar(160);

alter table workspace_agents
    add constraint fk_workspace_agents_model_provider
        foreign key (model_provider_id) references workspace_model_providers (id);

create index if not exists idx_task_executions_workspace_created_id
    on task_executions (workspace_id, created_at desc, id desc);

create index if not exists idx_tasks_workspace_id_desc
    on tasks (workspace_id, id desc);

create index if not exists idx_workspace_invites_workspace_id_desc
    on workspace_invites (workspace_id, id desc);

create index if not exists idx_chat_messages_workspace_session_id
    on chat_messages (workspace_id, chat_session_id, id);

create index if not exists idx_chat_messages_workspace_task_id
    on chat_messages (workspace_id, task_id, id);

create index if not exists idx_orchestration_sessions_workspace_id_desc
    on orchestration_sessions (workspace_id, id desc);
