create table users (
    id bigint generated by default as identity,
    email varchar(255) not null,
    google_sub varchar(100) not null,
    name varchar(100) not null,
    role varchar(20) not null,
    constraint users_pkey primary key (id),
    constraint uk_users_email unique (email),
    constraint uk_users_google_sub unique (google_sub),
    constraint users_role_check check (role in ('USER', 'ADMIN'))
);

create table workspaces (
    id bigint generated by default as identity,
    deleted_at timestamp(6) without time zone,
    description varchar(500),
    name varchar(100) not null,
    created_by_member_id bigint not null,
    constraint workspaces_pkey primary key (id)
);

create table workspace_members (
    id bigint generated by default as identity,
    joined_at timestamp(6) without time zone not null,
    role varchar(20) not null,
    member_id bigint not null,
    workspace_id bigint not null,
    constraint workspace_members_pkey primary key (id),
    constraint uk_workspace_members_workspace_member unique (workspace_id, member_id),
    constraint workspace_members_role_check check (role in ('ADMIN', 'MEMBER'))
);

create table member_profiles (
    id bigint generated by default as identity,
    avatar_hair_color varchar(7) not null,
    avatar_kind varchar(50) not null,
    avatar_shirt_color varchar(7) not null,
    avatar_skin_color varchar(7) not null,
    display_name varchar(100) not null,
    member_id bigint not null,
    constraint member_profiles_pkey primary key (id),
    constraint uk_member_profiles_member unique (member_id)
);

create table workspace_invites (
    id bigint generated by default as identity,
    accepted_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone not null,
    email varchar(255) not null,
    email_failed_at timestamp(6) without time zone,
    email_failure_reason varchar(500),
    expires_at timestamp(6) without time zone not null,
    revoked_at timestamp(6) without time zone,
    status varchar(20) not null,
    token varchar(255) not null,
    workspace_id bigint not null,
    constraint workspace_invites_pkey primary key (id),
    constraint uk_workspace_invites_token unique (token),
    constraint workspace_invites_status_check check (status in ('PENDING', 'ACCEPTED', 'EXPIRED', 'REVOKED'))
);

create table workspace_gateway_bindings (
    id bigint generated by default as identity,
    authenticated_at timestamp(6) without time zone,
    created_by_google_sub varchar(120) not null,
    deleted_at timestamp(6) without time zone,
    device_id varchar(120),
    device_name varchar(120),
    gateway_url varchar(300) not null,
    last_checked_at timestamp(6) without time zone,
    last_error text,
    last_status varchar(40),
    token text not null,
    workspace_id bigint not null,
    constraint workspace_gateway_bindings_pkey primary key (id),
