create table tasks (
    id bigint generated by default as identity,
    assigned_agent_id bigint,
    created_at timestamp(6) without time zone not null,
    created_by_google_sub varchar(120) not null,
    description varchar(1000),
    priority varchar(20) not null,
    source_ref varchar(240),
    status varchar(30) not null,
    title varchar(160) not null,
    task_type varchar(40) not null,
    updated_at timestamp(6) without time zone not null,
    workspace_id bigint not null,
    constraint tasks_pkey primary key (id),
    constraint tasks_priority_check check (priority in ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    constraint tasks_status_check check (status in (
        'REQUESTED', 'ASSIGNED', 'IN_PROGRESS', 'WAITING_USER', 'COMPLETED', 'FAILED', 'CANCELED'
    )),
    constraint tasks_task_type_check check (task_type in (
        'CODE_REVIEW', 'PR_REVIEW', 'BUG_FIX', 'FEATURE_IMPLEMENTATION', 'REFACTORING',
        'TEST_CREATION', 'DOCUMENTATION', 'PR_CREATION', 'OTHER'
    ))
);

create table task_executions (
    id bigint generated by default as identity,
